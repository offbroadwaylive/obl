// Builds the Arts People theme so the ticketing pages always match the site.
//
//   public/ap/ap-theme.css  tokens.css + @font-face + src/ap/ap.css
//                            (deployed with the site; Arts People links to it)
//   ap-out/head.html         paste into Arts People: HTML headers
//   ap-out/top.html          paste into Arts People: Top section
//   ap-out/footer.html       paste into Arts People: Footer
//
// The site address comes from astro.config.mjs (site + base), so after the
// domain cutover a rebuild produces snippets with the new address. Re-paste
// head/top/footer once at that point; CSS changes never need a re-paste.
//
// Run: npm run build:ap   (also runs automatically before every build)
// Custom domain snippets now: AP_SITE=https://offbroadwaylive.com AP_OUT=ap-out-domain npm run build:ap

import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

// Site address from astro.config.mjs
const config = read('astro.config.mjs');
const site = config.match(/site:\s*'([^']+)'/)?.[1];
const base = config.match(/base:\s*'([^']*)'/)?.[1] ?? '';
if (!site) throw new Error('Could not read site from astro.config.mjs');
// AP_SITE overrides the address (e.g. to build snippets for the custom domain
// before astro.config.mjs changes); AP_OUT sends the snippets to another folder.
const SITE = (process.env.AP_SITE || site + base).replace(/\/$/, '');
const OUT = process.env.AP_OUT || join(root, 'ap-out');

// Fonts: same faces the site self-hosts (src/lib/fonts.ts). The CSS sits in
// /ap/, so ../fonts/ resolves to the site's font folder on any domain.
// GitHub Pages sends Access-Control-Allow-Origin: *, so cross-origin fonts load.
const faces = [...read('src/lib/fonts.ts').matchAll(
  /family:\s*'([^']+)',\s*file:\s*'([^']+)',\s*weight:\s*(\d+),\s*style:\s*'(\w+)'/g,
)].map(([, family, file, weight, style]) =>
  `@font-face{font-family:'${family}';src:url('../fonts/${file}.woff2') format('woff2');font-weight:${weight};font-style:${style};font-display:swap}`,
);
if (faces.length === 0) throw new Error('No font faces found in src/lib/fonts.ts');

const css = [
  `/* Off Broadway Live theme for Arts People. Generated by scripts/build-ap-theme.mjs; edit src/ap/ap.css. */`,
  faces.join('\n'),
  read('src/styles/tokens.css'),
  read('src/ap/ap.css'),
].join('\n\n');

mkdirSync(join(root, 'public/ap'), { recursive: true });
writeFileSync(join(root, 'public/ap/ap-theme.css'), css);

// Navigation shared by the desktop bar and the mobile menu
const nav = [
  ['encore-supper-club/', 'ENCORE Supper Club'],
  ['calendar/', 'Calendar'],
  ['season-tickets/', 'Season Tickets'],
  ['menus/', 'Menus'],
  ['faqs/', 'FAQs'],
  ['contact/', 'Contact'],
].map(([path, label]) => `<a href="${SITE}/${path}">${label}</a>`).join('\n      ');

const fill = (s) => s.replaceAll('{{NAV}}', nav).replaceAll('{{SITE}}', SITE);

mkdirSync(OUT, { recursive: true });
for (const name of ['head', 'top', 'footer']) {
  writeFileSync(join(OUT, `${name}.html`), fill(read(`src/ap/${name}.html`)));
}
copyFileSync(join(root, 'src/ap/obl-logo.png'), join(OUT, 'obl-logo.png'));

console.log(`Arts People theme built for ${SITE}: public/ap/ap-theme.css, ${OUT}/{head,top,footer}.html`);
